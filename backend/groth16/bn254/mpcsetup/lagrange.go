// invertChunkFp returns the inverses of the Z coordinates of chunk using the
// Montgomery trick: one inversion per chunk. Points at infinity (Z=0) get a
// zero inverse marker.
func invertChunkFp(chunk []curve.G1Jac, buf []fp.Element) []fp.Element {
	buf = buf[:len(chunk)]
	var acc fp.Element
	acc.SetOne()
	for i := range chunk {
		if chunk[i].Z.IsZero() {
			buf[i].SetZero()
			continue
		}
		buf[i].Set(&acc)
		acc.Mul(&acc, &chunk[i].Z)
	}
	var inv fp.Element
	inv.Inverse(&acc)
	for i := len(chunk) - 1; i >= 0; i-- {
		if chunk[i].Z.IsZero() {
			continue
		}
		var zInv fp.Element
		zInv.Mul(&inv, &buf[i])
		inv.Mul(&inv, &chunk[i].Z)
		buf[i] = zInv
	}
	return buf
}

