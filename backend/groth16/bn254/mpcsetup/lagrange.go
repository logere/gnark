// windowBits returns the 2-bit window of k starting at bit position 2*w.
func windowBits(k *[4]uint64, w int) uint64 {
	// 2w is always even, so the window never straddles a word boundary.
	word := uint(w) >> 5
	off := uint(2*w) & 63
	return (k[word] >> off) & 3
}

